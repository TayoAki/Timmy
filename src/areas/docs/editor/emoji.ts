export const ALL_EMOJI = EMOJI.flatMap((g) => g.items);

export const searchEmoji = (q: string) => {
  const s = q.trim().toLowerCase();
  if (!s) return null;
  return ALL_EMOJI.filter(([e, w]) => e === s || w.split(' ').some((x) => x.startsWith(s)));
};

/** A random friendly icon for "Add icon". */
export const randomEmoji = () => {
  const pool = EMOJI[0]!.items.concat(EMOJI[1]!.items).map((x) => x[0]);
  return pool[Math.floor(Math.random() * pool.length)]!;
};
